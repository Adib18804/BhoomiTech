def render_report_pdf(data: dict) -> bytes:
    """Render the persisted snapshot into a bilingual-friendly PDF.
    `language` picks the primary wording; both scripts render correctly."""
    lang = data.get("language", "en")
    L = SECTION_LABELS[lang]
    case = data["case"]
    land = data["land_identity"]

    pdf = _pdf_factory()

    # Branding band
    pdf.set_fill_color(22, 101, 52)  # government-inspired green
    pdf.set_text_color(255, 255, 255)
    pdf.set_font("NB", "B", 18)
    pdf.cell(0, 12, f"  {BRAND_NAME}", fill=True, new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("NB", "", 10)
    pdf.cell(0, 8, f"  {REPORT_TITLES[lang]}", fill=True, new_x="LMARGIN", new_y="NEXT")
    pdf.set_text_color(0, 0, 0)
    pdf.ln(3)

    # NOT-a-certificate banner (cautious wording, required)
    pdf.set_fill_color(255, 249, 219)
    pdf.set_draw_color(217, 119, 6)
    pdf.set_font("NB", "B", 9)
    pdf.multi_cell(w=0, h=5, text=NOT_CERTIFICATE[lang], border=1, fill=True,
                   new_x="LMARGIN", new_y="NEXT")
    pdf.ln(1)
    pdf.set_font("NB", "", 9)
    pdf.multi_cell(w=0, h=5, text=SYNTHETIC_NOTICE[lang], new_x="LMARGIN", new_y="NEXT")
    pdf.ln(2)

    # Summary block
    _h1(pdf, L["summary"])
    risk = case.get("overall_risk_level")
    pdf.set_font("NB", "B", 13)
    pdf.set_text_color(*SEVERITY_COLOR.get(
        "critical" if risk == "CRITICAL_SIGNAL" else
        "high" if risk == "HIGH_ATTENTION" else
        "medium" if risk in ("REVIEW_REQUIRED",) else
        "success" if risk == "LOW_CONCERN" else "info", (55, 65, 81)))
    pdf.multi_cell(w=0, h=7, text=f"{L['risk_status']}: {RISK_LABELS.get(risk, {}).get(lang, risk or '-')}",
                   new_x="LMARGIN", new_y="NEXT")
    pdf.set_text_color(0, 0, 0)
    if case.get("risk_score") is not None:
        _kv(pdf, L["risk_score"], case["risk_score"], lang)
    _kv(pdf, L["case_id"], case.get("case_id"), lang)
    _kv(pdf, L["generated"], datetime.utcnow().strftime("%Y-%m-%d %H:%M UTC"), lang)
