# ---------------------------------------------------------------- persistence
def next_report_id(db: Session) -> str:
    # Same allocation race as verification case ids: count()+1 is only safe if
    # the count-and-insert is atomic. Two concurrent report generations (e.g.
    # React StrictMode firing the request twice) could otherwise pick the same
    # id and the second would fail the unique constraint. The transaction-scoped
    # advisory lock serialises the allocation and is released on commit/rollback.
    db.execute(text("SELECT pg_advisory_xact_lock(:lock_id)"), {"lock_id": 723102})
    count = db.query(Report).count()
    return f"BT-RPT-{datetime.utcnow().year}-{count + 1:06d}"


def generate_report(db: Session, case: VerificationCase, language: str = "en") -> Report:
    """Build the snapshot, render the PDF, persist both on the existing
    Report model, and return the Report row."""
    data = build_report_data(db, case, language=language)
    data["report_id"] = next_report_id(db)
    pdf_bytes = render_report_pdf(data)

    report = Report(
        report_id=data["report_id"],
        user_id=case.user_id,
        verification_case_id=case.id,
        report_type="verification",
        format="pdf",
        title=f"{BRAND_NAME} {REPORT_TITLES[language]} - {case.case_id}",
        content_json=data,
        content_pdf=pdf_bytes,
        file_size_bytes=len(pdf_bytes),
        language=language,
        generated_by_user_id=case.user_id,
        accessed_at=datetime.utcnow(),
    )
    db.add(report)
    db.commit()
    db.refresh(report)
    return report
